def build_zsh_highlighting(p: dict[str, str]) -> str:
    lines = [
        f"# {HEADER}",
        "# rose-pine-geist theme for zsh-syntax-highlighting.",
        "# Source this BEFORE zsh-syntax-highlighting itself.",
        "ZSH_HIGHLIGHT_HIGHLIGHTERS=(main cursor)",
        "typeset -gA ZSH_HIGHLIGHT_STYLES",
        "",
    ]
    for key, role, extra in ZSH_STYLES:
        if role is None:
            lines.append(key)
            continue
        style = f"fg={p[role]}" + (f",{extra}" if extra else "")
        lines.append(f"ZSH_HIGHLIGHT_STYLES[{key}]='{style}'")
    lines.append("")
    return "\n".join(lines)


def build_zsh_prompt(p: dict[str, str]) -> str:
    lines = [
        f"# {HEADER}",
        "# rose-pine-geist palette as shell variables, for prompts etc.",
    ]
    for k, v in p.items():
        lines.append(f'export RPG_{k.upper()}="{v}"')
    lines += [
        "",
        "# Example prompt:",
        '# PS1="%F{$RPG_FOAM}%n@%m%f:%F{$RPG_TEXT}%~%f %F{$RPG_ROSE}$ %f"',
        "",
    ]
    return "\n".join(lines)


def build_obsidian(p: dict[str, str]) -> str:
    # Obsidian exposes code-block colors as --code-* variables that both
    # the editor and reading view respect. The two selectors outrank
    # Minimal's scheme selector (.minimal-flexoki-dark.theme-dark) or tie
    # it and win by load order (snippets load after themes).
    roles = [
        ("normal", "text"),
        ("comment", "muted"),
        ("function", "rose"),
        ("important", "love"),
        ("keyword", "pine"),
        ("operator", "subtle"),
        ("property", "foam"),
        ("punctuation", "subtle"),
        ("string", "gold"),
        ("tag", "foam"),
        ("value", "rose"),
    ]
    # Scoped to code-BLOCK containers only (pre = reading view,
    # .HyperMD-codeblock = editor lines): CSS vars resolve from the nearest
    # ancestor, so fenced blocks get rose-pine colors while inline code and
    # backgrounds stay stock flexoki (warm), untouched by the snippet.
    lines = [
        f"/* {HEADER}",
        "   rose-pine-geist code-block colors for Obsidian (dark mode only).",
        "   Fenced blocks only — inline code stays stock. */",
        ".theme-dark pre,",
        ".theme-dark .HyperMD-codeblock {",
        # Alpha, not a palette hex: composites over the page color so the
        # recess inherits flexoki's warmth. 0.15 subtle .. 0.35 pronounced.
        "\t--code-background: rgba(0, 0, 0, 0.15);",
    ]
    lines += [f"\t--code-{name}: {p[role]};" for name, role in roles]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> None:
    with open(ROOT / "palette.toml", "rb") as f:
        palette = tomllib.load(f)["palette"]

    targets = {
        "nvim/lua/rose-pine-geist/palette.lua": build_nvim(palette),
        "ghostty/themes/rose-pine-geist": build_ghostty(palette),
        "zsh/rose-pine-geist-highlighting.zsh": build_zsh_highlighting(palette),
        "zsh/rose-pine-geist-prompt.zsh": build_zsh_prompt(palette),
        "obsidian/rose-pine-geist-code.css": build_obsidian(palette),
    }
    for rel, content in targets.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {rel}")


if __name__ == "__main__":
    main()
