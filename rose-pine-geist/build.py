"""Generate all rose-pine-geist theme targets from palette.toml.

Usage: uv run build.py
Stdlib only (tomllib requires Python 3.11+, hence the uv pin above).
"""

import tomllib
from pathlib import Path

ROOT = Path(__file__).parent

HEADER = "Generated by `uv run build.py` from palette.toml. Do not edit by hand."


def build_nvim(p: dict[str, str]) -> str:
    # Keys mirror rose-pine/neovim's lua/rose-pine/palette.lua (main variant).
    order = [
        ("_nc", p["nc"]),
        ("base", p["base"]),
        ("surface", p["surface"]),
        ("overlay", p["overlay"]),
        ("muted", p["muted"]),
        ("subtle", p["subtle"]),
        ("text", p["text"]),
        ("love", p["love"]),
        ("gold", p["gold"]),
        ("rose", p["rose"]),
        ("pine", p["pine"]),
        ("foam", p["foam"]),
        ("iris", p["iris"]),
        ("leaf", p["leaf"]),
        ("highlight_low", p["highlight_low"]),
        ("highlight_med", p["highlight_med"]),
        ("highlight_high", p["highlight_high"]),
    ]
    lines = [f"-- {HEADER}", "return {"]
    lines += [f'\t{k} = "{v}",' for k, v in order]
    lines += ['\tnone = "NONE",', "}", ""]
    return "\n".join(lines)


def build_ghostty(p: dict[str, str]) -> str:
    # ANSI mapping mirrors the Rose Pine theme bundled with Ghostty,
    # except 0 (black) = surface so it stays distinct from the background.
    ansi = [
        p["surface"], p["love"], p["pine"], p["gold"],
        p["foam"], p["iris"], p["rose"], p["text"],
        p["muted"], p["love"], p["pine"], p["gold"],
        p["foam"], p["iris"], p["rose"], p["text"],
    ]
    lines = [f"# {HEADER}"]
    lines += [f"palette = {i}={c}" for i, c in enumerate(ansi)]
    lines += [
        f"background = {p['base']}",
        f"foreground = {p['text']}",
        # Accent-colored cursor, Vesper-style.
        f"cursor-color = {p['rose']}",
        f"cursor-text = {p['base']}",
        f"selection-background = {p['highlight_med']}",
        f"selection-foreground = {p['text']}",
        "",
    ]
    return "\n".join(lines)


